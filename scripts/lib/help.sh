#!/usr/bin/env bash

cmd_help() {
    echo "Usage: ironbook [command] [options]"
    echo ""
    echo "Commands:"
    echo "  get-tree                Generate directory structure."
    echo "  get-codebase            Generate the entire codebase in codebase.txt."
    echo "  update-version <ver>    Update project versions."
    echo "  check-update <ver> <manifest>  Check an update manifest for a newer release (no download/install)."
    echo "  build <ver> [options]   Build, package, and sign a release."
    echo "    --no-sign             Skip signing release files."
    echo "  help                    Show this help menu."
    echo "  setup [options]         Sets up the project after being cloned."
    echo "    --no-env-files        Skip setting up .env files."
    echo "    --no-system-commands  Skip checking for any required dependencies."
    echo "    --no-mingw            Skip setting up MingW. Set to be true if --no-system-commands is passed."
    echo "    --no-curl             Skip setting up Curl. Set to be true if --no-system-commands is passed."
    echo "    --no-git              Skip setting up Git. Set to be true if --no-system-commands is passed."
    echo "    --no-docker           Skip setting up Docker and Docker Compose. Set to be true if --no-system-commands is passed."
    echo "    --no-docker-services  Skip setting up Docker services. Set to be true if --no-docker-services or --no-system-commands is passed."
    echo "    --no-mise             Skip setting up Mise."
    echo "    --no-mise-install     Skip installing sub project dependencies from Mise. Set to be true if --no-mise is passed."
    echo "    --no-project-setup    Skip running setup tasks of sub projects from Mise. Set to be true if --no-mise is passed."
    echo "    --no-git-hooks        Skip setting up pre-commit hooks. Set to be true if --no-mise or --no-mise-install is passed."
    echo "    --no-pre-commit-test  Skip running the pre-commit tests. Set to be true if --no-mise or --no-project-setup is passed."
}
